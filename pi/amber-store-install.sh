USER_NAME=${SUDO_USER:-amber}; [ "$USER_NAME" = root ] && USER_NAME=amber
USER_HOME=$(getent passwd "$USER_NAME" | cut -d: -f6)
say() { echo " * $*"; }
# run a program inside the logged-in desktop (so its window appears on screen)
run_in_desktop() {
    local pid envs=() v val
    pid=$(pgrep -u "$USER_NAME" -x plasmashell | head -n 1)
    [ -z "$pid" ] && pid=$(pgrep -u "$USER_NAME" -x lxqt-panel | head -n 1)
    [ -z "$pid" ] && return 1
    for v in DISPLAY XAUTHORITY DBUS_SESSION_BUS_ADDRESS XDG_RUNTIME_DIR; do
        val=$(tr '\0' '\n' < "/proc/$pid/environ" | grep "^$v=" | head -n 1)
        [ -n "$val" ] && envs+=("$val")
    done
    sudo -u "$USER_NAME" env "${envs[@]}" setsid "$@" >/dev/null 2>&1 < /dev/null &
}

