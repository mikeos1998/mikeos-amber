#!/bin/bash
# Mike OS: Amber Lite - switches the desktop to a much lighter one (LXQt + Openbox) with the
# Amber look, and adds the Mike OS Wi-Fi app. Made for the Raspberry Pi 3's 1 GB of RAM.
#
#   sudo bash amber-lite.sh          switch to Amber Lite (needs internet - it helps you connect)
#   sudo bash amber-lite.sh --undo   go back to the full KDE desktop
#
# Your files, apps, games, gadgets and sounds stay the same either way.

if [ "$(id -u)" != 0 ]; then echo "Run it with sudo:  sudo bash $0"; exit 1; fi
USER_NAME=${SUDO_USER:-amber}; [ "$USER_NAME" = root ] && USER_NAME=amber
USER_HOME=$(getent passwd "$USER_NAME" | cut -d: -f6)
AUTOLOGIN=/etc/sddm.conf.d/10-mikeos-autologin.conf
say() { echo " * $*"; }

set_session() {   # $1 = lxqt or plasma
    mkdir -p /etc/sddm.conf.d
    printf '[Autologin]\nUser=%s\nSession=%s\n' "$USER_NAME" "$1" > "$AUTOLOGIN"
}

ask_reboot() {
    echo
    read -r -p "Restart now to finish? [Y/n] " answer
    case "$answer" in
        [nN]*) echo "OK - restart later with:  sudo reboot" ;;
        *) reboot ;;
    esac
}

# run a program inside the logged-in desktop (so its window appears on screen)
run_in_desktop() {
    local pid envs=() v val
    pid=$(pgrep -u "$USER_NAME" -x plasmashell | head -n 1)
    [ -z "$pid" ] && pid=$(pgrep -u "$USER_NAME" -x lxqt-panel | head -n 1)
    [ -z "$pid" ] && return 1
    for v in DISPLAY XAUTHORITY DBUS_SESSION_BUS_ADDRESS XDG_RUNTIME_DIR; do
        val=$(tr '\0' '\n' < "/proc/$pid/environ" | grep "^$v=" | head -n 1)
        [ -n "$val" ] && envs+=("$val")
    done
    sudo -u "$USER_NAME" env "${envs[@]}" setsid "$@" >/dev/null 2>&1 < /dev/null &
}

online() { curl -s -o /dev/null --max-time 8 http://deb.debian.org/debian/ || curl -s -o /dev/null --max-time 8 https://www.google.com; }

if [ "${1:-}" = "--undo" ]; then
    echo "=== Switching back to the full KDE desktop ==="
    set_session plasma
    say "Next start-up uses KDE again. (Run this script without --undo to go back to Amber Lite.)"
    ask_reboot
    exit 0
fi

