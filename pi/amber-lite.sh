AMBER_LITE_PAYLOAD
if [ -n "$USER_HOME" ] && [ -d "$USER_HOME" ]; then
    mkdir -p "$USER_HOME/Desktop"
    install -m 755 -o "$USER_NAME" -g "$USER_NAME" /etc/skel/Desktop/Wi-Fi.desktop "$USER_HOME/Desktop/Wi-Fi.desktop"
fi

# ------------------------------------------------ 2. internet (to download the lighter desktop)
if ! online; then
    echo
    say "The Pi isn't online yet. Opening the Wi-Fi app - pick your network and connect."
    say "(Or plug in an Ethernet cable.) Waiting up to 10 minutes..."
    run_in_desktop python3 /usr/share/mikeos-amber/apps/wifi.py || \
        say "Open \"Wi-Fi\" from the desktop or start menu to connect."
    for _ in $(seq 1 120); do
        online && break
        sleep 5
    done
    if ! online; then
        echo "Still no internet. Connect to Wi-Fi, then run this script again."
        exit 1
    fi
    say "Online!"
fi

# ------------------------------------------------ 3. the lighter desktop
say "Downloading the lighter desktop (LXQt + Openbox). This takes a few minutes on a Pi..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
if ! apt-get install -y -q --no-install-recommends lxqt-core openbox gvfs gvfs-daemons libglib2.0-bin qterminal lximage-qt qpdfview featherpad lxqt-archiver screengrab speedcrunch; then
    echo "!! The download didn't work, so nothing was switched. Check the internet connection and run this again."
    exit 1
fi
say "Adding Chromium (the smoother browser on a Pi)"
apt-get install -y -q chromium-browser || apt-get install -y -q chromium || \
    say "Chromium couldn't be installed - Firefox stays the browser."
if [ ! -f /usr/share/xsessions/lxqt.desktop ]; then
    echo "!! LXQt didn't install properly, so nothing was switched."
    exit 1
fi

# ------------------------------------------------ 4. Amber look for Lite
say "Applying the Amber look"
for f in /etc/xdg/autostart/mikeos-amber-*.desktop; do       # startup sound, Welcome, Gadgets
    sed -i 's/^OnlyShowIn=KDE;$/OnlyShowIn=KDE;LXQt;/' "$f"
done
sh /usr/share/mikeos-amber/lite/apply-user.sh /etc/skel
if [ -n "$USER_HOME" ] && [ -d "$USER_HOME" ]; then
    sh /usr/share/mikeos-amber/lite/apply-user.sh "$USER_HOME"
    chown -R "$USER_NAME:$USER_NAME" "$USER_HOME/.config"
fi

# ------------------------------------------------ 5. start Amber Lite at login
set_session lxqt
say "Done. From the next start-up the Pi uses Amber Lite."
say "To go back to the full KDE desktop later:  sudo bash $0 --undo"
ask_reboot
